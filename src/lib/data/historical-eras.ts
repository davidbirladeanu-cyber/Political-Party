export interface HistoricalEntity {
  id: string;
  name: string;
  shortName?: string;
  englishName: string;
  emblem: string;
  color: string;
  borderColor?: string;
  ruler: string;
  rulerTitle: string;
  capital: string;
  governmentType: string;
  summary: string;
  keyEvents: string[];
  territoryNumericCodes: string[];
  modernCountriesIncluded: string[];
}

export interface HistoricalEra {
  year: number; // Negative for BC, positive for AD
  label: string; // e.g. "3500 î.Hr."
  title: string;
  period:
    | "Antichitate Timpurie"
    | "Epoca Clasică"
    | "Evul Mediu"
    | "Epoca Marilor Descoperiri"
    | "Epoca Modernă"
    | "Secolul XX"
    | "Prezent";
  description: string;
  entities: HistoricalEntity[];
}

export function formatYear(year: number): string {
  if (year < 0) return `${Math.abs(year)} î.Hr.`;
  if (year === 0) return "Anul 0";
  if (year >= 2026) return "2026 d.Hr. (Prezent)";
  return `${year} d.Hr.`;
}

